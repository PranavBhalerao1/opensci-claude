
import pandas as pd

raw_ck = pd.read_csv('analysis/checkpoint_stats.csv')

# ── Step 3: Write LaTeX tabular ───────────────────────────────────────────────
latex_lines = [
    r'% Table 1: Checkpoint Accuracy Summary',
    r'% Study: Augmentation Benefit Direction in the 5-Epoch Underfitting Regime',
    r'% Generated by T4.4 (Visualization and Results Engineer), 2026-10-10',
    r'% Values: test accuracy in percentage points (2 d.p.); gaps = aug − no-aug (pp)',
    r'',
    r'\begin{table}[ht]',
    r'\centering',
    r'\caption{Checkpoint test-accuracy summary at epochs 5, 10, 20, and 30.',
    r'  Test accuracy (\%) for no-augmentation and augmentation conditions per seed,',
    r'  per-seed accuracy gap (aug\,$-$\,no-aug, pp), and mean gap across seeds.',
    r'  All gap values are negative: augmentation imposes a penalty',
    r'  throughout the entire 30-epoch training run.}',
    r'\label{tab:checkpoint_summary}',
    r'\begin{tabular}{c rr r rr r r}',
    r'\toprule',
    r' & \multicolumn{3}{c}{Seed 42} & \multicolumn{3}{c}{Seed 123} & \\',
    r'\cmidrule(lr){2-4} \cmidrule(lr){5-7}',
    (r'Epoch'
     r' & No-aug (\%) & Aug (\%) & Gap (pp)'
     r' & No-aug (\%) & Aug (\%) & Gap (pp)'
     r' & Mean Gap (pp) \\'),
    r'\midrule',
]

# Data rows
for _, r in raw_ck.iterrows():
    ep   = int(r['epoch'])
    n42  = f"{r['noaug_s42_test']:.2f}"
    a42  = f"{r['aug_s42_test']:.2f}"
    # use LaTeX minus for negatives
    g42_val = r['gap_s42']
    g42  = (f"$+{g42_val:.2f}$" if g42_val >= 0 else f"$-${abs(g42_val):.2f}")
    n123 = f"{r['noaug_s123_test']:.2f}"
    a123 = f"{r['aug_s123_test']:.2f}"
    g123_val = r['gap_s123']
    g123 = (f"$+{g123_val:.2f}$" if g123_val >= 0 else f"$-${abs(g123_val):.2f}")
    mg_val = r['mean_gap']
    mg   = (f"$+{mg_val:.2f}$" if mg_val >= 0 else f"$-${abs(mg_val):.2f}")
    latex_lines.append(
        f"{ep} & {n42} & {a42} & {g42} & {n123} & {a123} & {g123} & {mg} \\\\"
    )

latex_lines += [
    r'\bottomrule',
    r'\end{tabular}',
    r'\end{table}',
]

latex_content = '\n'.join(latex_lines) + '\n'
print(latex_content)

with open('analysis/table1_checkpoint_summary.tex', 'w') as f:
    f.write(latex_content)
print("\nWrote analysis/table1_checkpoint_summary.tex")

# Verify required strings present
assert r'\begin{tabular}' in latex_content
assert r'\end{tabular}' in latex_content
assert r'\toprule' in latex_content
assert r'\bottomrule' in latex_content
print("LaTeX structure verified OK")
