"""
src/make_subsets.py
===================
Generate stratified train/val subset index arrays for Fashion-MNIST.

Provenance
----------
Dataset : Fashion-MNIST (Zalando SE, MIT License)
Source  : torchvision.datasets.FashionMNIST  →  http://fashion-mnist.s3-website.eu-central-1.amazonaws.com/
Access  : 2026-10-09  (auto-downloaded to data/)
Script  : T1.2 — Study "How Augmentation Benefit Scales with Training Set Size"
"""

import os
import numpy as np
from sklearn.model_selection import StratifiedShuffleSplit
import torchvision
import torchvision.transforms as transforms

# ── 1. Load Fashion-MNIST training labels ──────────────────────────────────────
print("Loading Fashion-MNIST training set …")
dataset = torchvision.datasets.FashionMNIST(
    root="data/",
    train=True,
    download=True,
    transform=transforms.ToTensor(),
)
y_train = np.array(dataset.targets)          # shape (60000,)
N_TOTAL  = len(y_train)                      # 60 000
N_CLASSES = 10
print(f"  y_train shape : {y_train.shape}")
print(f"  unique labels : {np.unique(y_train)}")
print(f"  class counts  : {np.bincount(y_train)}")

# ── 2. Configuration ───────────────────────────────────────────────────────────
SIZES = [500, 1_000, 2_500, 5_000, 10_000, 30_000, 60_000]
SEEDS = [42, 123]

arrays_dict: dict[str, np.ndarray] = {}

# ── 3. Build stratified subsets ────────────────────────────────────────────────
for seed in SEEDS:
    rng = np.random.RandomState(seed)

    for N in SIZES:
        per_class = N // N_CLASSES          # exact quota per class

        # ── 3a. Select N indices with exactly per_class per class ────────────
        selected: list[np.ndarray] = []
        for c in range(N_CLASSES):
            class_idxs = np.where(y_train == c)[0]
            chosen = rng.choice(class_idxs, size=per_class, replace=False)
            selected.append(chosen)
        subset_idxs = np.concatenate(selected)   # length == N (= per_class * 10)

        # ── 3b. StratifiedShuffleSplit 90/10 on the selected indices ─────────
        y_subset = y_train[subset_idxs]
        sss = StratifiedShuffleSplit(n_splits=1, test_size=0.1, random_state=seed)
        train_pos, val_pos = next(sss.split(subset_idxs, y_subset))

        train_idx = subset_idxs[train_pos]
        val_idx   = subset_idxs[val_pos]

        key_tr = f"train_{N}_{seed}"
        key_va = f"val_{N}_{seed}"
        arrays_dict[key_tr] = train_idx
        arrays_dict[key_va] = val_idx

        print(
            f"  N={N:>6d}  seed={seed}  "
            f"train={len(train_idx)}  val={len(val_idx)}  "
            f"(per_class_quota={per_class})"
        )

# ── 4. Save ────────────────────────────────────────────────────────────────────
out_path = "data/subset_indices.npz"
np.savez(out_path, **arrays_dict)
print(f"\nSaved {len(arrays_dict)} arrays → {out_path}")

# ── 5. Verify completeness ─────────────────────────────────────────────────────
loaded = np.load(out_path)
keys   = sorted(loaded.files)
print(f"\nTotal keys in npz : {len(keys)}  (expected 28)")
for k in keys:
    print(f"  {k:30s}  shape={loaded[k].shape}")

assert len(keys) == 28, f"Expected 28 keys, got {len(keys)}"

# ── 6. Class-balance report & assertion for N=500 and N=1000 ─────────────────
REPORT_SIZES = [500, 1_000]
CLASS_NAMES = [
    "T-shirt/top", "Trouser", "Pullover", "Dress", "Coat",
    "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot",
]

report_lines: list[str] = []
report_lines.append("=" * 72)
report_lines.append("Fashion-MNIST Stratified Subset — Class-Balance Check")
report_lines.append("Generated by src/make_subsets.py  |  Date: 2026-10-09")
report_lines.append("=" * 72)

for N in REPORT_SIZES:
    for seed in SEEDS:
        key_tr  = f"train_{N}_{seed}"
        tr_idx  = loaded[key_tr]
        y_tr    = y_train[tr_idx]
        counts  = np.bincount(y_tr, minlength=N_CLASSES)

        per_class_quota = N // N_CLASSES          # quota used in step 3a
        # After 90/10 StratifiedShuffleSplit the training split gets 90% of each
        # class stratum, i.e. floor(per_class_quota * 0.9)
        expected_tr = int(np.round(per_class_quota * 0.9))

        report_lines.append("")
        report_lines.append(f"N={N}, seed={seed}  |  train size={len(tr_idx)}")
        report_lines.append(f"  Expected ~{expected_tr} samples per class")
        report_lines.append(f"  {'Class':<16} {'ID':>3}  {'Count':>6}  {'OK?':>5}")
        report_lines.append(f"  {'-'*40}")

        all_ok = True
        for c, (name, cnt) in enumerate(zip(CLASS_NAMES, counts)):
            lo = expected_tr - 1
            hi = expected_tr + 1
            ok = lo <= cnt <= hi
            if not ok:
                all_ok = False
            status = "✓" if ok else f"✗ [{lo},{hi}]"
            report_lines.append(f"  {name:<16} {c:>3}  {cnt:>6}  {status:>5}")

        report_lines.append(
            f"  → All classes balanced: {'YES' if all_ok else 'NO'}"
        )

        # Hard assertion only for N=500 (per acceptance criteria)
        if N == 500:
            per_class_quota_500 = 500 // 10           # = 50
            expected_tr_500 = int(np.round(per_class_quota_500 * 0.9))  # = 45
            lo, hi = 44, 46   # ±1 around 45
            bad = [(c, cnt) for c, cnt in enumerate(counts) if not (lo <= cnt <= hi)]
            assert not bad, (
                f"Balance assertion FAILED for N=500, seed={seed}: "
                f"out-of-range classes {bad}"
            )
            report_lines.append(
                f"  ✓ N=500 assertion passed: all per-class counts in [{lo},{hi}]"
            )

report_lines.append("")
report_lines.append("=" * 72)
report_lines.append("All balance checks passed.")
report_lines.append("=" * 72)

report_text = "\n".join(report_lines) + "\n"
with open("data/class_balance_check.txt", "w") as fh:
    fh.write(report_text)

print("\n" + report_text)
print("✓ data/class_balance_check.txt written.")
print("✓ All acceptance checks passed.")
